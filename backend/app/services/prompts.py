# 独立调用：从纯文本推断脚本（当只需要脚本时用，MVP 未启用）
# --------------------------------------------------------------------------


def build_title_messages(paper_text: str) -> list[dict[str, str]]:
    return [
        {
            "role": "system",
            "content": "你从论文正文中提取标题。只输出标题本身，不要引号、不要解释、不要句号。",
        },
        {"role": "user", "content": paper_text[:2000]},
    ]
